package com.lordmystery.gacha.data

/**
 * Card rarity tiers mapped to Beyonder Sequences.
 * COMMON = Sequence 9-8, RARE = Sequence 7, EPIC = Sequence 5-4,
 * LEGENDARY = Sequence 3-2, MYTHIC = Sequence 1-0 (Angel / King of Angels)
 */
enum class Rarity(val labelAr: String, val labelEn: String, val color: Int, val stars: Int) {
    COMMON("شائع", "Common", 0xFF9E9E9E.toInt(), 1),
    RARE("نادر", "Rare", 0xFF42A5F5.toInt(), 2),
    EPIC("ملحمي", "Epic", 0xFFAB47BC.toInt(), 3),
    LEGENDARY("أسطوري", "Legendary", 0xFFFFB300.toInt(), 4),
    MYTHIC("إلهي", "Mythic", 0xFFFF5252.toInt(), 5)
}

data class GameCard(
    val id: String,
    val nameAr: String,
    val nameEn: String,
    val pathway: String,       // e.g. "مسار الأحمق"
    val pathwayEn: String,     // e.g. "Fool Pathway"
    val sequence: Int,         // 0..9
    val rarity: Rarity,
    val atk: Int,
    val def: Int,
    val hp: Int,
    val spirit: Int,           // max spirituality
    val skillName: String,
    val skillDesc: String,
    val skillCost: Int,
    val skillPower: Int,       // damage multiplier x100
    val lore: String,
    val emoji: String,
    val isLimited: Boolean = false
)

